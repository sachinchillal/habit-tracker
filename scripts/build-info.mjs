// Writes src/environments/build-info.ts with the app version, git commit and build time.
// Runs before every serve/build/test (see package.json scripts). The output is gitignored.
//
// - version: from package.json. Change it only when releasing, with `npm version patch|minor|major`.
// - commit / dirty: from git. `dirty` means the build included uncommitted changes.
// - builtAt: the moment this script ran, as ISO 8601 UTC.

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'environments', 'build-info.ts');

function git(args) {
  try {
    return execSync(`git ${args}`, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return null;
  }
}

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const commit = git('rev-parse --short HEAD') ?? 'unknown';
const status = git('status --porcelain');
const dirty = status !== null && status.length > 0;
const builtAt = new Date().toISOString();

const buildInfo = { version, commit, dirty, builtAt };

writeFileSync(
  outFile,
  `// Generated by scripts/build-info.mjs on every serve/build. Do not edit or commit.\n` +
  `export const buildInfo = ${JSON.stringify(buildInfo, null, 2)} as const;\n`,
);

console.log(`build-info: v${version} (${commit}${dirty ? '-dirty' : ''}) ${builtAt}`);
